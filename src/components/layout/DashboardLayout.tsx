export function DashboardLayout({
  children,
  role: roleProp,
  user,
  title,
  breadcrumbs,
}: DashboardLayoutProps) {
  const { branding } = useBranding();
  const role = roleProp || user?.role || "RETAILER";
  const [isOpenMobile, setIsOpenMobile] = useState(false);
  const [isCollapsedDesktop, setIsCollapsedDesktop] = useState(false);

  const menuItems = React.useMemo((): MenuItem[] => {
    switch (role) {
      case "SUPER_ADMIN":
        return SUPER_ADMIN_MENU;
      case "MASTER_ADMIN":
        return MASTER_ADMIN_MENU;
      case "ADMIN":
        return ADMIN_MENU;
      case "SUPER_DISTRIBUTOR":
        return SUPER_DISTRIBUTOR_MENU;
      case "MASTER_DISTRIBUTOR":
        return MASTER_DISTRIBUTOR_MENU;
      case "DISTRIBUTOR":
        return DISTRIBUTOR_MENU;
      case "RETAILER":
      default:
        return RETAILER_MENU;
    }
  }, [role]);

  const handleCloseMobile = React.useCallback(() => setIsOpenMobile(false), []);
  const handleOpenMobile = React.useCallback(() => setIsOpenMobile(true), []);
  const handleToggleDesktop = React.useCallback(() => setIsCollapsedDesktop((prev) => !prev), []);

  return (
    <ToastProvider>
      <div className="min-h-screen bg-gray-50 flex flex-col antialiased">
        {/* Sidebar */}
        <Sidebar
          menuItems={menuItems}
          isOpenMobile={isOpenMobile}
          onCloseMobile={handleCloseMobile}
          isCollapsedDesktop={isCollapsedDesktop}
          onToggleDesktop={handleToggleDesktop}
          user={user}
        />

        {/* Main Content Area */}
        <div
          className={cn(
            "flex flex-1 flex-col transition-all duration-200 ease-out gpu-composite",
            isCollapsedDesktop ? "lg:pl-20" : "lg:pl-64"
          )}
        >
          {/* Header */}
          <Header
            title={title}
            breadcrumbs={breadcrumbs}
            user={user}
            onOpenMobileMenu={handleOpenMobile}
          />

          {/* Page Body */}
          <main className="flex-1 p-4 sm:p-6 lg:p-8 max-w-7xl w-full mx-auto">
            {children}
          </main>

          {/* Footer */}
          <footer className="py-4 px-6 text-center text-xs text-gray-400 border-t border-gray-200 bg-white">
            © {new Date().getFullYear()} {branding?.appName || "Recharge Pro"} B2B Fintech Portal. All rights reserved.
          </footer>
        </div>
      </div>
    </ToastProvider>
  );
}

export default DashboardLayout;
